"""AdventureWorks OLTP (subset) -> PostgreSQL, ready for Lakeflow Connect CDC.

Source: Microsoft sql-server-samples, samples/databases/adventure-works/oltp-install-script
(MIT License), pinned to one commit. The SQL Server install script bulk-loads these
CSV files; this module converts the same files for PostgreSQL:

  - 16 tables from Person / Sales / Production / Purchasing, all with primary keys
  - SQL Server types -> PostgreSQL (bit -> boolean, money -> numeric(19,4),
    uniqueidentifier -> uuid, xml -> text, datetime -> timestamp)
  - computed columns (SalesOrderNumber, TotalDue, LineTotal, Customer.AccountNumber)
    are kept as plain columns with the values from the CSV, so logical replication
    carries them like any other column
  - Address.SpatialLocation (geography) is dropped
  - Sales.SalesTerritory.[Group] becomes territorygroup (GROUP is reserved)
  - names are lower case, so no quoting is needed in PostgreSQL or in Databricks

Used by the 01_load_adventureworks notebook. Run locally to print the DDL:
    python aw_loader.py --print-ddl > schema.sql
"""

