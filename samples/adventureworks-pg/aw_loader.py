SCHEMAS = sorted({t.schema for t in TABLES})


def ddl() -> str:
    parts = [
        "-- Generated by aw_loader.py --print-ddl. AdventureWorks OLTP subset for PostgreSQL.",
        f"-- Source CSVs: microsoft/sql-server-samples@{SOURCE_COMMIT}",
        "",
    ]
    parts += [f"CREATE SCHEMA IF NOT EXISTS {s};" for s in SCHEMAS]
    parts.append("")
    for t in TABLES:
        parts += [t.ddl(), ""]
        if t.replica_identity_full:
            parts += [f"ALTER TABLE {t.qualified} REPLICA IDENTITY FULL;", ""]
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# CSV parsing
# ---------------------------------------------------------------------------


def decode(raw: bytes) -> str:
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return raw.decode("utf-16")
    return raw.decode("utf-8-sig")


def parse_rows(text: str) -> list[list[str]]:
    """Two layouts in the install script: tab / newline, and '+|' / '&|' + newline
    (used where values contain tabs or newlines, e.g. XML columns)."""
    if "+|" in text[:4096]:
        records = text.split("&|\n")
        if records and records[-1].endswith("&|"):
            records[-1] = records[-1][:-2]
        return [r.split("+|") for r in records if r.strip()]
    return [
        line.rstrip("\r").split("\t")
        for line in text.split("\n")
        if line.strip("\r") != ""
    ]


def convert(table: Table, fields: list[str]) -> list[str | None]:
    if len(fields) != len(table.columns):
        raise ValueError(
            f"{table.csv}: expected {len(table.columns)} fields, got {len(fields)}"
        )
    # Empty field = NULL, as in the SQL Server bulk load.
    return [
        (v if v != "" else None) for v, c in zip(fields, table.columns) if c is not None
    ]


def fetch(
    csv_name: str, base_url: str = SOURCE_BASE_URL, cache_dir: str | None = None
) -> bytes:
    if cache_dir:
        import os

        path = os.path.join(cache_dir, csv_name)
        if os.path.exists(path):
            with open(path, "rb") as f:
                return f.read()
    with urllib.request.urlopen(f"{base_url}/{csv_name}", timeout=120) as resp:
        return resp.read()


