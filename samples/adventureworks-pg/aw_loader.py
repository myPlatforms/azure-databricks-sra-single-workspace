@dataclass
class Table:
    schema: str
    name: str
    csv: str
    # (column, PostgreSQL type) in CSV field order. None = CSV field is dropped.
    columns: list[tuple[str, str] | None]
    primary_key: list[str]
    # FULL for tables with large text values (TOAST), per the connector docs.
    replica_identity_full: bool = False
    identity_column: str | None = None
    load_columns: list[str] = field(init=False)

    def __post_init__(self) -> None:
        self.load_columns = [c[0] for c in self.columns if c is not None]

    @property
    def qualified(self) -> str:
        return f"{self.schema}.{self.name}"

    def ddl(self) -> str:
        cols = [f"    {c[0]} {c[1]}" for c in self.columns if c is not None]
        cols.append(
            f"    CONSTRAINT pk_{self.name} PRIMARY KEY ({', '.join(self.primary_key)})"
        )
        return (
            f"CREATE TABLE IF NOT EXISTS {self.qualified} (\n"
            + ",\n".join(cols)
            + "\n);"
        )


