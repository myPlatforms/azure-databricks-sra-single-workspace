def create_schema(conn, drop_existing: bool = False) -> None:
    with conn.cursor() as cur:
        if drop_existing:
            for s in SCHEMAS:
                cur.execute(f"DROP SCHEMA IF EXISTS {s} CASCADE")
        cur.execute(ddl())
    conn.commit()


def load_table(conn, table: Table, cache_dir: str | None = None) -> int:
    rows = [
        convert(table, r)
        for r in parse_rows(decode(fetch(table.csv, cache_dir=cache_dir)))
    ]
    with conn.cursor() as cur:
        cur.execute(f"TRUNCATE {table.qualified}")
        with cur.copy(
            f"COPY {table.qualified} ({', '.join(table.load_columns)}) FROM STDIN"
        ) as copy:
            for row in rows:
                copy.write_row(row)
        if table.identity_column:
            # Loaded with explicit IDs: move the identity past them so new rows work.
            cur.execute(
                f"SELECT setval(pg_get_serial_sequence('{table.qualified}', '{table.identity_column}'), "
                f"(SELECT COALESCE(MAX({table.identity_column}), 0) + 1 FROM {table.qualified}), false)"
            )
    conn.commit()
    return len(rows)


def load_all(conn, cache_dir: str | None = None, log=print) -> dict[str, int]:
    counts = {}
    for t in TABLES:
        counts[t.qualified] = load_table(conn, t, cache_dir=cache_dir)
        log(f"{t.qualified}: {counts[t.qualified]} rows")
    return counts


def setup_replication(
    admin_conn,
    database: str,
    replication_user: str,
    replication_password: str,
    publication: str = "databricks_publication",
) -> None:
    """Source setup from the Lakeflow Connect PostgreSQL docs, run as the server admin
    (table owner). The replication slot is created separately, as the replication user."""
    from psycopg import sql

    with admin_conn.cursor() as cur:
        # Azure Database for PostgreSQL: the admin is not a superuser and needs the
        # REPLICATION attribute itself before it can create a role that has it.
        cur.execute("ALTER ROLE CURRENT_USER WITH REPLICATION")
        cur.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (replication_user,))
        verb = "ALTER" if cur.fetchone() else "CREATE"
        cur.execute(
            sql.SQL("{} ROLE {} WITH LOGIN REPLICATION PASSWORD {}").format(
                sql.SQL(verb),
                sql.Identifier(replication_user),
                sql.Literal(replication_password),
            )
        )
        user = sql.Identifier(replication_user)
        cur.execute(
            sql.SQL("GRANT CONNECT ON DATABASE {} TO {}").format(
                sql.Identifier(database), user
            )
        )
        for s in SCHEMAS:
            schema = sql.Identifier(s)
            cur.execute(sql.SQL("GRANT USAGE ON SCHEMA {} TO {}").format(schema, user))
            cur.execute(
                sql.SQL("GRANT SELECT ON ALL TABLES IN SCHEMA {} TO {}").format(
                    schema, user
                )
            )
            cur.execute(
                sql.SQL(
                    "ALTER DEFAULT PRIVILEGES IN SCHEMA {} GRANT SELECT ON TABLES TO {}"
                ).format(schema, user)
            )
        for catalog_table in (
            "pg_publication",
            "pg_replication_slots",
            "pg_namespace",
            "pg_class",
            "pg_attribute",
            "pg_type",
            "pg_index",
        ):
            cur.execute(
                sql.SQL("GRANT SELECT ON pg_catalog.{} TO {}").format(
                    sql.Identifier(catalog_table), user
                )
            )

        for t in TABLES:
            identity = "FULL" if t.replica_identity_full else "DEFAULT"
            cur.execute(f"ALTER TABLE {t.qualified} REPLICA IDENTITY {identity}")

        # FOR ALL TABLES needs a superuser; FOR TABLE needs table ownership (the admin).
        table_list = sql.SQL(", ").join(sql.SQL(t.qualified) for t in TABLES)
        cur.execute("SELECT 1 FROM pg_publication WHERE pubname = %s", (publication,))
        if cur.fetchone():
            cur.execute(
                sql.SQL("ALTER PUBLICATION {} SET TABLE {}").format(
                    sql.Identifier(publication), table_list
                )
            )
        else:
            cur.execute(
                sql.SQL("CREATE PUBLICATION {} FOR TABLE {}").format(
                    sql.Identifier(publication), table_list
                )
            )
    admin_conn.commit()


def create_slot(replication_conn, slot: str = "databricks_slot") -> bool:
    """Create the pgoutput slot as the replication user (after the publication).
    Returns False when it already exists."""
    with replication_conn.cursor() as cur:
        cur.execute("SELECT 1 FROM pg_replication_slots WHERE slot_name = %s", (slot,))
        if cur.fetchone():
            return False
        cur.execute(
            "SELECT pg_create_logical_replication_slot(%s, 'pgoutput')", (slot,)
        )
    replication_conn.commit()
    return True


def verify(admin_conn, replication_user: str, publication: str, slot: str) -> dict:
    """The checks from the connector's 'Verify the configuration' section."""
    out = {}
    with admin_conn.cursor() as cur:
        cur.execute("SHOW wal_level")
        out["wal_level"] = cur.fetchone()[0]
        cur.execute(
            "SELECT rolreplication FROM pg_roles WHERE rolname = %s",
            (replication_user,),
        )
        out["replication_user_has_replication"] = cur.fetchone()[0]
        cur.execute(
            "SELECT count(*) FROM pg_publication_tables WHERE pubname = %s",
            (publication,),
        )
        out["publication_tables"] = cur.fetchone()[0]
        cur.execute(
            "SELECT slot_type, plugin, active FROM pg_replication_slots WHERE slot_name = %s",
            (slot,),
        )
        out["slot"] = cur.fetchone()
        cur.execute(
            "SELECT n.nspname || '.' || c.relname, c.relreplident FROM pg_class c "
            "JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE c.relkind = 'r' AND n.nspname = ANY(%s) ORDER BY 1",
            (SCHEMAS,),
        )
        out["replica_identity"] = dict(cur.fetchall())
    return out


